export type IconName = keyof typeof ICONS;

export interface IconProps extends Omit<FontAwesomeIconProps, "icon" | "size"> {
  name: IconName;
  /** Altura em px (largura proporcional). Use `fw` pra caixa fixa. */
  size?: number;
  /** Largura fixa de 1.25em — alinha ícones diferentes numa lista. */
  fw?: boolean;
}

export function Icon({ name, size = 16, fw, className, style, ...rest }: IconProps) {
  return (
    <FontAwesomeIcon
      icon={ICONS[name]}
      fixedWidth={fw}
      aria-hidden={rest["aria-label"] ? undefined : true}
      focusable={false}
      className={cn("inline-block shrink-0 align-[-0.125em]", className)}
      style={{ fontSize: size, ...style }}
      {...rest}
    />
  );
}
